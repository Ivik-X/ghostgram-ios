import Foundation
import UIKit

public final class CheckmarkColorManager {
    public static let shared = CheckmarkColorManager()

    private let defaults = UserDefaults.standard

    private init() {}

    public var customColor: UIColor? {
        get {
            if let hex = defaults.string(forKey: "FontCustomization.checkmarkColorHex") {
                return UIColor(hex: hex)
            }
            return nil
        }
        set {
            defaults.set(newValue?.hexString, forKey: "FontCustomization.checkmarkColorHex")
        }
    }
}

private extension UIColor {
    convenience init?(hex: String) {
        var hexSanitized = hex.trimmingCharacters(in: .whitespacesAndNewlines)
        hexSanitized = hexSanitized.replacingOccurrences(of: "#", with: "")

        var rgb: UInt64 = 0
        guard Scanner(string: hexSanitized).scanHexInt64(&rgb) else { return nil }

        let r = CGFloat((rgb & 0xFF0000) >> 16) / 255.0
        let g = CGFloat((rgb & 0x00FF00) >> 8) / 255.0
        let b = CGFloat(rgb & 0x0000FF) / 255.0

        self.init(red: r, green: g, blue: b, alpha: 1.0)
    }

    var hexString: String {
        var r: CGFloat = 0
        var g: CGFloat = 0
        var b: CGFloat = 0
        var a: CGFloat = 0
        getRed(&r, green: &g, blue: &b, alpha: &a)
        return String(format: "#%02lX%02lX%02lX", lroundf(Float(r * 255)), lroundf(Float(g * 255)), lroundf(Float(b * 255)))
    }
}
